#!/usr/bin/env python3
"""Generate platform values from Jianxin's existing design tokens."""
import argparse
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--platform', choices=['both', 'android', 'ios'], default='both')
platform = parser.parse_args().platform
contract = json.loads((root.parent / 'frontend/.design').read_text(encoding='utf-8'))
colors = contract['tokens']['color']
spacing = contract['tokens']['spacing']
# rem => native points/dp at the system's default 16-unit body size.
space = {key: float(value.removesuffix('rem')) * 16 for key, value in spacing.items()}
def argb(value):
    if value.startswith('rgba('):
        red, green, blue, alpha = value[5:-1].split(',')
        return (round(float(alpha) * 255) << 24) | (int(red) << 16) | (int(green) << 8) | int(blue)
    return 0xff000000 | int(value.lstrip('#'), 16)
swift = 'import SwiftUI\n\n// Generated by mobile/tools/generate_theme.py.\nenum MailTheme {\n'
for name, value in colors.items():
    rgb = argb(value)
    swift += f'    static let {name} = Color(red: {((rgb >> 16)&255)/255:.8f}, green: {((rgb >> 8)&255)/255:.8f}, blue: {(rgb&255)/255:.8f}, opacity: {((rgb >> 24)&255)/255:.8f})\n'
for key, value in space.items():
    swift += f'    static let space{key}: CGFloat = {value:g}\n'
swift += '    static let target: CGFloat = 44\n}\n'
if platform in {'both', 'ios'}:
    (root / 'ios/Jianxin/MailTheme.swift').write_text(swift, encoding='utf-8')
kotlin = 'package com.jianxin.mail\n\n// Generated by mobile/tools/generate_theme.py.\nobject MailTheme {\n'
android_colors = {**colors, **json.loads((root / '.design').read_text(encoding='utf-8'))['platforms']['android']['colors']}
for name, value in android_colors.items():
    kotlin += f'    val {name} = 0x{argb(value):08x}.toInt()\n'
for key, value in space.items():
    kotlin += f'    const val space{key} = {int(value)}\n'
kotlin += '    const val target = 48\n}\n'
if platform in {'both', 'android'}:
    (root / 'android/app/src/main/java/com/jianxin/mail/MailTheme.kt').write_text(kotlin, encoding='utf-8')

theme_resources = {'primary', 'primaryForeground', 'selected', 'onPrimaryContainer', 'fill', 'canvas', 'text', 'surfaceContainer', 'muted', 'outline', 'danger', 'recessed', 'line'}
resources = '<resources>\n' + ''.join(f'    <color name="mail_{name}">#{argb(value):08x}</color>\n' for name, value in android_colors.items() if name in theme_resources) + '</resources>\n'
if platform in {'both', 'android'}:
    (root / 'android/app/src/main/res/values/colors.xml').write_text(resources, encoding='utf-8')
